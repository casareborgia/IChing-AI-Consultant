"""상용구 지표의 자가 검증 (네트워크·DB 없음).

`scripts/measure_boilerplate.py`는 실사용 신고를 그대로 세는 자다 — "괘가 다른데 같은
문구가 나온다". 자가 틀리면 그 뒤 판단이 전부 틀리므로, 답이 뻔한 두 극단을 넣어
지표가 갈라지는지 붙들어 둔다.

  극단 A — 괘마다 자기 효사의 말을 한 경우 (괘가 일한다)
  극단 B — 어느 괘든 같은 상담 문구로 마무리한 경우 (통념으로 후퇴)

**대조군이 이 자의 핵심이다.** 상담 답변에는 괘와 무관한 뼈대가 원래 있다 — 사연을
되짚는 공감 도입과 되묻기 마무리. 그것까지 증상으로 세면 멀쩡한 답변이 나쁘게 찍힌다.
그래서 절대값이 아니라 "같은 괘를 두 번 돌린 쌍"과의 차이를 본다. 아래 테스트가
지키는 것이 바로 그 성질이다 — 뼈대는 두 극단에 똑같이 들어 있는데도 갈라져야 한다.
"""

import pytest

from scripts.measure_boilerplate import 분석, 어절들, ngrams

효사 = {
    "수산건": "왕의 신하가 어려움을 무릅쓰는 것은 제 한 몸을 위한 일이 아니기 때문입니다",
    "천산둔": "누런 소가죽으로 묶어 아무도 풀 수 없듯 뜻만은 굳게 붙들라는 자리입니다",
    "지뢰복": "돌아옴이 머지않아 뉘우침에 이르지 않는다는 되돌아옴의 자리입니다",
}
사연들 = [
    "30년 하던 가게를 접고 업종을 바꿀지 고민입니다",
    "7년 만난 사람과 헤어질지 계속 갈지 모르겠습니다",
]
공감 = "말씀을 들으니 그동안 마음이 얼마나 무거우셨을지 짐작이 됩니다"
마무리 = "지금 가장 마음에 걸리는 것은 무엇인가요"
통념 = "지금은 잠시 멈춰 서서 스스로의 내면을 다지는 시간입니다"


def _rows(모드):
    out = []
    for q in 사연들:
        for 배치, 효 in 효사.items():
            for 회차 in (0, 1):
                흔들림 = "" if 회차 == 0 else " 조금 더 들여다보면"
                본문 = 효 if 모드 == "괘가일한다" else 통념
                out.append({
                    "질문": q, "배치": 배치, "회차": 회차, "근거": 효,
                    "답변": f"{공감}{흔들림} {본문} {마무리}",
                })
    return out


def test_괘마다_다른_말을_하면_대조군과_벌어진다():
    r = 분석(_rows("괘가일한다"))
    차 = r["같은괘_공유"] - r["다른괘_공유"]

    assert 차 > 0.2, "괘를 바꾼 쌍이 대조군보다 뚜렷이 덜 닮아야 한다"
    assert r["다른괘_공유"] < r["같은괘_공유"]


def test_어느_괘든_같은_말을_하면_대조군과_붙는다():
    r = 분석(_rows("통념으로후퇴"))
    차 = r["같은괘_공유"] - r["다른괘_공유"]

    assert abs(차) < 0.1, "괘를 바꾼 것이 아무 일도 하지 않았다는 뜻이어야 한다"
    assert r["전역_덮임"] > 0.9


def test_공감_뼈대만으로는_두_극단이_갈리지_않는다():
    """뼈대는 양쪽에 똑같이 들어 있다. 그런데도 지표가 갈려야 자가 쓸모 있다."""
    일함 = 분석(_rows("괘가일한다"))
    후퇴 = 분석(_rows("통념으로후퇴"))

    # 대조군(같은 괘 반복)은 두 조건에서 비슷해야 한다 — 뼈대와 회차 흔들림만 다르다
    assert abs(일함["같은괘_공유"] - 후퇴["같은괘_공유"]) < 0.1
    # 갈리는 것은 괘가 다른 쌍이다
    assert 후퇴["다른괘_공유"] - 일함["다른괘_공유"] > 0.2


def test_사연을_되짚는_말은_상용구로_세지_않는다():
    """상담사는 내담자의 말을 되짚는다. 그건 통념 후퇴가 아니라 공감이다."""
    사연 = 사연들[0]
    rows = [
        {"질문": 사연, "배치": 배치, "회차": 0, "근거": 효,
         "답변": f"{사연} 그 마음이 느껴집니다 {효}"}
        for 배치, 효 in 효사.items()
    ]
    r = 분석(rows)

    질문_문구 = {" ".join(g) for g in ngrams(어절들(사연))}
    나온_문구 = {문구 for 문구, *_ in r["넓은_문구"]}
    assert not (질문_문구 & 나온_문구), "질문에 있던 어절 뭉치가 상용구로 잡혔다"


def test_답변이_비어도_터지지_않는다():
    rows = [{"질문": 사연들[0], "배치": "수산건", "회차": 0, "근거": "근거", "답변": ""},
            {"질문": 사연들[0], "배치": "천산둔", "회차": 0, "근거": "근거", "답변": ""}]
    r = 분석(rows)
    assert r["다른괘_공유"] == pytest.approx(0.0)
