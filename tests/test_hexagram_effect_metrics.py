"""반증 하네스의 자가 검증 (네트워크·DB 없음).

`scripts/compare_hexagram_effect.py`는 "괘가 답변을 실제로 바꾸는가"를 재는 자다.
자 자체가 틀리면 그 뒤의 판단이 전부 틀리므로, 답이 뻔한 두 극단을 넣어 지표가
갈라지는지 붙들어 둔다.

  극단 A — 답변이 근거를 그대로 옮긴 경우 (괘가 일한다)
  극단 B — 어느 괘든 같은 말을 한 경우 (괘가 아무 일도 안 한다)

실제 답변은 이 둘 사이에 앉는다. 여기서 지키는 것은 "A와 B가 갈라진다"까지다.
"""

import pytest

from scripts.compare_hexagram_effect import 유사도, 포함도

근거 = {
    "수산건": "나아가면 어려움이고 돌아오면 명예롭다. 왕의 신하가 간난하고 또 간난하니 "
              "제 몸을 위한 까닭이 아니다. 마땅히 기다려야 한다.",
    "천산둔": "누런 소의 가죽으로 잡아매니 벗기거나 풀 수 없다. 물러나는 때에도 뜻을 굳게 함이다.",
    "지뢰복": "돌아옴이 머지않아 뉘우침에 이르지 않는다. 그 도를 반복하여 이레 만에 돌아온다.",
}
공감 = "오랜 시간 쌓아오신 경험은 사라지지 않습니다. 막막한 그 마음이 느껴집니다. "
통념 = 공감 + "지금은 잠시 멈춰 서서 내면을 다지는 시간입니다. 무엇이 걸리시나요?"


def 판별(답변들):
    """각 답변이 자기 괘의 근거와 가장 닮았는지. 보고() 안의 판정과 같은 계산이다."""
    맞은수 = 0
    for 이름, 답 in 답변들.items():
        점수 = {k: 포함도(답, e) for k, e in 근거.items()}
        맞은수 += int(max(점수, key=점수.get) == 이름)
    return 맞은수


def test_근거를_옮긴_답변은_자기_괘로_판별된다():
    답변들 = {k: 공감 + f"주역은 지금을 이렇게 봅니다. {e}" for k, e in 근거.items()}

    assert 판별(답변들) == len(근거)
    for k, 답 in 답변들.items():
        assert 포함도(답, 근거[k]) > 0.9


def test_어느_괘든_같은_말을_하면_우연_수준으로_떨어진다():
    답변들 = {k: 통념 for k in 근거}

    assert 판별(답변들) <= 1, "우연(1/3) 수준이어야 한다"
    for k in 근거:
        assert 포함도(통념, 근거[k]) < 0.1, "근거가 답변에 닿지 않았다"


def test_답변_쌍_유사도가_두_극단을_가른다():
    """괘가 일하면 답변이 서로 달라지고, 통념으로 후퇴하면 똑같아진다."""
    갈린답 = [공감 + e for e in 근거.values()]
    같은답 = [통념] * len(근거)

    def 평균쌍(xs):
        쌍 = [유사도(a, b) for i, a in enumerate(xs) for b in xs[i + 1:]]
        return sum(쌍) / len(쌍)

    assert 평균쌍(같은답) == pytest.approx(1.0)
    assert 평균쌍(갈린답) < 0.7


def test_빈_문자열에도_터지지_않는다():
    assert 포함도("", "근거") == 0.0
    assert 포함도("답변", "") == 0.0
    assert 유사도("", "") == 0.0
